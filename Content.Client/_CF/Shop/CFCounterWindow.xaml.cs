using System.Linq;
using Content.Shared.CF.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Shop;

/// <summary>
/// A merchant's counter, as its merchant sees it: what adventurers have placed on it, its market price, the
/// merchant's own price in four boxes (pp, gp, sp, cp) filled with the market price, and a Buy button. The coins are
/// laid on the counter. Rows are kept while the same goods lie there, so a refresh never wipes what was typed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CFCounterWindow : DefaultWindow
{
    private const int CoinBoxWidth = 38;
    private const int PriceWidth = 4 * CoinBoxWidth + 3 * 2;

    /// <summary>Copper per coin, in the order of the boxes: pp, gp, sp, cp.</summary>
    private static readonly int[] CoinCopper = { 1000, 100, 10, 1 };

    private static readonly string[] CoinNames = { "pp", "gp", "sp", "cp" };

    public event Action<NetEntity, int>? OnBuy;
    public event Action? OnStored;
    public event Action? OnShop;

    private readonly Dictionary<NetEntity, (Control Row, LineEdit[] Boxes)> _rows = new();
    private List<NetEntity> _order = new();

    public CFCounterWindow()
    {
        RobustXamlLoader.Load(this);
        Header.AddChild(CFTradeTable.Header(
            (Loc.GetString("cf-counter-col-market"), CFTradeTable.CostWidth),
            (Loc.GetString("cf-counter-col-your-price"), PriceWidth),
            (Loc.GetString("cf-shop-col-buy"), CFTradeTable.ButtonWidth)));
        StoredButton.OnPressed += _ => OnStored?.Invoke();
        ShopButton.OnPressed += _ => OnShop?.Invoke();
    }

    public void UpdateState(CFMerchantCounterState state, int wallet)
    {
        var order = new List<NetEntity>();
        foreach (var offer in state.Offers)
        {
            if (order.Contains(offer.Item))
                continue;

            order.Add(offer.Item);
            if (!_rows.ContainsKey(offer.Item))
                _rows[offer.Item] = BuildRow(offer);
        }

        foreach (var gone in new List<NetEntity>(_rows.Keys))
        {
            if (!order.Contains(gone))
                _rows.Remove(gone);
        }

        // Only rebuild when the goods changed, so a box being typed in keeps its focus.
        if (!order.SequenceEqual(_order))
        {
            _order = order;
            Rows.RemoveAllChildren();
            foreach (var item in order)
            {
                Rows.AddChild(_rows[item].Row);
            }
        }

        EmptyLabel.Visible = state.Offers.Count == 0;
        WalletLabel.Text = Loc.GetString("cf-counter-wallet", ("amount", CFCoins.FormatWallet(wallet)));
        StoredButton.Text = Loc.GetString("cf-counter-stored", ("count", state.Stored.Count));
    }

    /// <summary>The copper the four boxes add up to. Empty or unreadable boxes count as 0.</summary>
    public static int ReadPrice(LineEdit[] boxes)
    {
        var total = 0;
        for (var i = 0; i < boxes.Length; i++)
        {
            if (int.TryParse(boxes[i].Text, out var count) && count > 0)
                total += Math.Min(count, 100_000) * CoinCopper[i];
        }

        return total;
    }

    private (Control Row, LineEdit[] Boxes) BuildRow(CFCounterEntry offer)
    {
        var item = offer.Item;
        var wanted = offer.Copper > 0;
        var boxes = new LineEdit[CoinCopper.Length];
        var price = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SetWidth = PriceWidth,
            MinWidth = PriceWidth,
            MaxWidth = PriceWidth,
            HorizontalExpand = false,
            SeparationOverride = 2,
        };

        var left = offer.Copper;
        for (var i = 0; i < CoinCopper.Length; i++)
        {
            var count = left / CoinCopper[i];
            left -= count * CoinCopper[i];
            boxes[i] = new LineEdit
            {
                Text = count.ToString(),
                PlaceHolder = CoinNames[i],
                ToolTip = CoinNames[i],
                SetWidth = CoinBoxWidth,
                MinWidth = CoinBoxWidth,
                MaxWidth = CoinBoxWidth,
                Editable = wanted,
            };
            price.AddChild(boxes[i]);
        }

        var row = CFTradeTable.Item(offer,
            CFTradeTable.Cell(CFTradeTable.Price(offer.Copper), CFTradeTable.CostWidth),
            price,
            CFTradeTable.Button(Loc.GetString("cf-shop-buy"), !wanted, () => OnBuy?.Invoke(item, ReadPrice(boxes))));
        return (row, boxes);
    }
}
