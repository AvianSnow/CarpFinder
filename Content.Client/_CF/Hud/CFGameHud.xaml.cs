using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Hud;

[GenerateTypedNameReferences]
public sealed partial class CFGameHud : UIWidget
{
    private readonly Button[] _filters;
    private readonly Dictionary<Button, (Color Idle, Color Hot)> _colors = new();
    private bool _selecting;

    public CFGameHud()
    {
        RobustXamlLoader.Load(this);
        MouseFilter = MouseFilterMode.Ignore;
        _filters = [ActionsFilter, SpellsFilter];
        _colors[ActionsFilter] = (new Color(46, 120, 52), new Color(96, 176, 88));
        _colors[SpellsFilter] = (new Color(36, 72, 140), new Color(90, 150, 210));
        Select(ActionsFilter);

        foreach (var filter in _filters)
        {
            var chosen = filter;
            chosen.OnPressed += _ => Select(chosen);
        }

        DividerLeft.PanelOverride = Divider();
        ActionPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = new Color(72, 72, 76, 110),
            BorderColor = new Color(190, 190, 194, 150),
            BorderThickness = new Thickness(1),
        };
    }

    private void Select(Button selected)
    {
        if (_selecting)
            return;

        _selecting = true;
        foreach (var filter in _filters)
        {
            filter.Pressed = filter == selected;
            var colors = _colors[filter];
            filter.StyleBoxOverride = Flat(filter.Pressed ? colors.Hot : colors.Idle);
        }

        _selecting = false;
    }

    private static StyleBoxFlat Flat(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
            ContentMarginLeftOverride = 6,
            ContentMarginRightOverride = 6,
            ContentMarginTopOverride = 3,
            ContentMarginBottomOverride = 3,
        };
    }

    private static StyleBoxFlat Divider()
    {
        return new StyleBoxFlat
        {
            BackgroundColor = new Color(150, 36, 36),
        };
    }
}
