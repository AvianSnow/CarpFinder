/// <summary>
/// The deck that slides out above the bar. The All tab shows basic actions, spells and features, and the numbered
/// hotbar side by side, with dividers that share out the columns. The other tabs show one category at full width.
/// Custom is the numbered hotbar. While an action is dragged the hotbar appears as well, so it can be dropped on a slot
/// from any tab. With Basic, Class or Spells chosen, the number keys use that tab's first row, and Shift with them its
/// second (<see cref="TryKeyed"/>). Items are not on the deck: they are used in hand.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CFHudDeck : Control
{
    private const float Slot = CFDeckLayout.Slot;
    private const int BasicKey = 0;
    private const int FeaturesKey = 1;
    private const int ListKey = 2;

    /// <summary>The number keys reach the first two rows of a tab: ten keys, then ten with Shift.</summary>
    private const int KeyedSlots = 20;
    private const float RefreshSeconds = 0.2f;
    private const string IconFontPath = "/Fonts/_CF/FontAwesome/fa-solid-900.ttf";

    private const char IconMinus = '';
    private const char IconPlus = '';
    private const char IconLock = '';
    private const char IconPin = '';

    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IConfigurationManager _config = default!;
    [Dependency] private IResourceCache _cache = default!;

    private readonly Dictionary<CFDeckTab, Button> _tabs = new();
    private readonly Dictionary<CFDeckTab, (Color Idle, Color Hot)> _tabColors = new();
    private readonly Button[] _rankButtons = new Button[CFDeckSorter.FocusGroup + 1];
    private readonly List<Entity<ActionComponent>> _common = new();
    private readonly List<Entity<ActionComponent>> _features = new();
    private readonly SortedDictionary<int, List<Entity<ActionComponent>>> _spellGroups = new();
    private readonly List<EntityUid> _listed = new();
    private readonly string[] _shownKeys = new string[ListKey + 1];

    private ActionUIController? _controller;
    private CFDeckWidths _widths = new();
    private CFDeckTab _tab = CFDeckTab.All;
    private int _spellGroup;
    private int _rows;
    private bool _customOnly;
    private float _refresh;

    /// <summary>The pin was toggled.</summary>
    public event Action<bool>? PinChanged;

    public bool Pinned => PinButton.Pressed;

    /// <summary>An action or a divider is being dragged, so the deck must not close.</summary>
    public bool IsDragging => Controller.IsDragging || Divider0.Dragging || Divider1.Dragging;

    private ActionUIController Controller => _controller ??= UserInterfaceManager.GetUIController<ActionUIController>();

    public CFHudDeck()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;

        Frame.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = new Color(32, 32, 38, 225),
            BorderColor = new Color(96, 96, 104, 220),
            BorderThickness = new Thickness(1),
        };

        AddTab(CFDeckTab.All, TabAll, new Color(84, 60, 112), new Color(150, 116, 196));
        AddTab(CFDeckTab.Common, TabCommon, new Color(46, 120, 52), new Color(96, 176, 88));
        AddTab(CFDeckTab.ClassFeatures, TabClass, new Color(140, 96, 28), new Color(214, 158, 64));
        AddTab(CFDeckTab.Spells, TabSpells, new Color(36, 72, 140), new Color(90, 150, 210));
        AddTab(CFDeckTab.Custom, TabCustom, new Color(72, 72, 80), new Color(132, 132, 144));
        BuildRankRow();

        var icons = new VectorFont(_cache.GetResource<FontResource>(IconFontPath), 12);
        SetIcon(RowsLess, IconMinus, icons);
        SetIcon(RowsMore, IconPlus, icons);
        SetIcon(LockButton, IconLock, icons);
        SetIcon(PinButton, IconPin, icons);

        RowsLess.OnPressed += _ => SetRows(_rows - 1);
        RowsMore.OnPressed += _ => SetRows(_rows + 1);
        LockButton.OnToggled += args => SetLocked(args.Pressed);
        PinButton.OnToggled += args =>
        {
            _config.SetCVar(CFCVars.HudDeckPinned, args.Pressed);
            _config.SaveToFile();
            PinChanged?.Invoke(args.Pressed);
        };
        Trackers.RankPressed += rank => SelectSpellGroup(rank);
        Divider0.Moved = steps => MoveDivider(0, steps);
        Divider1.Moved = steps => MoveDivider(1, steps);
        BasicPager.PageChanged += page => BasicGrid.Page = page;
        FeaturesPager.PageChanged += page => FeaturesGrid.Page = page;
        CustomPager.PageChanged += page => Bar.ActionsContainer.Page = page;

        PinButton.Pressed = _config.GetCVar(CFCVars.HudDeckPinned);
        LockButton.Pressed = _config.GetCVar(CFCVars.HudDeckLocked);
        Controller.CFLocked = LockButton.Pressed;
        _widths = CFDeckWidths.Parse(_config.GetCVar(CFCVars.HudDeckColumns));
        SetRows(_config.GetCVar(CFCVars.HudDeckRows), save: false);
        SelectTab(CFDeckTab.All);
    }

    /// <summary>For a body with no Pathfinder stats: the numbered hotbar is all there is to show.</summary>
    public void SetCustomOnly(bool customOnly)
    {
        if (_customOnly == customOnly)
            return;

        _customOnly = customOnly;
        foreach (var (tab, button) in _tabs)
        {
            button.Disabled = customOnly && tab != CFDeckTab.Custom;
        }

        SelectTab(customOnly ? CFDeckTab.Custom : CFDeckTab.All);
    }

    public void SetBook(CFSpellbookComponent? book)
    {
        Trackers.SetBook(_tab is CFDeckTab.All or CFDeckTab.Spells ? book : null);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        Sections.Visible = _tab is CFDeckTab.All or CFDeckTab.Custom || Controller.IsDragging;

        _refresh -= args.DeltaSeconds;
        if (_refresh > 0f)
            return;

        _refresh = RefreshSeconds;
        RefreshContents();
        UpdatePagers();
        UpdateSlotStates();
    }

    private void AddTab(CFDeckTab tab, Button button, Color idle, Color hot)
    {
        _tabs[tab] = button;
        _tabColors[tab] = (idle, hot);
        button.ToggleMode = true;
        button.OnPressed += _ => SelectTab(tab);
    }

    private void BuildRankRow()
    {
        for (var group = 0; group <= CFDeckSorter.FocusGroup; group++)
        {
            var chosen = group;
            var button = new Button
            {
                Text = GroupLabel(group),
                ToolTip = GroupTooltip(group),
                ToggleMode = true,
                HorizontalExpand = true,
                MinHeight = 22f,
            };
            button.OnPressed += _ => SelectSpellGroup(chosen);
            _rankButtons[group] = button;
            RankRow.AddChild(button);
        }
    }

    private static string GroupLabel(int group)
    {
        return group switch
        {
            0 => Loc.GetString("cf-hud-deck-cantrips"),
            CFDeckSorter.FocusGroup => Loc.GetString("cf-hud-deck-focus"),
            _ => Loc.GetString("cf-hud-deck-rank-short", ("rank", group), ("suffix", Ordinal(group))),
        };
    }

    private static string GroupTooltip(int group)
    {
        return group is 0 or CFDeckSorter.FocusGroup
            ? GroupLabel(group)
            : Character.CFSpellsTab.RankTitle(group);
    }

    private static string Ordinal(int rank)
    {
        return rank % 10 == 1 && rank != 11 ? "st"
            : rank % 10 == 2 && rank != 12 ? "nd"
            : rank % 10 == 3 && rank != 13 ? "rd"
            : "th";
    }

    public void SelectTab(CFDeckTab tab)
    {
        _tab = tab;
        foreach (var (key, button) in _tabs)
        {
            button.Pressed = key == tab;
            var colors = _tabColors[key];
            button.StyleBoxOverride = Flat(key == tab ? colors.Hot : colors.Idle);
        }

        var all = tab == CFDeckTab.All;
        RankRow.Visible = tab == CFDeckTab.Spells;
        ListHolder.Visible = tab is not (CFDeckTab.All or CFDeckTab.Custom);
        Sections.Visible = all || tab == CFDeckTab.Custom;
        BasicSection.Visible = all;
        FeaturesSection.Visible = all;
        Divider0.Visible = all;
        Divider1.Visible = all;
        CustomTitle.Visible = all;

        ApplyLayout();
        ForgetShown();
    }

    private void ForgetShown()
    {
        Array.Clear(_shownKeys);
        _refresh = 0f;
    }

    private void SelectSpellGroup(int group)
    {
        if (_tab != CFDeckTab.Spells)
            SelectTab(CFDeckTab.Spells);

        _spellGroup = group;
        ForgetShown();
    }

    private void SetRows(int rows, bool save = true)
    {
        _rows = Math.Clamp(rows, 1, CFActionGrid.MaxRows);
        ApplyLayout();
        RowsLess.Disabled = _rows <= 1;
        RowsMore.Disabled = _rows >= CFActionGrid.MaxRows;
        if (!save)
            return;

        _config.SetCVar(CFCVars.HudDeckRows, _rows);
        _config.SaveToFile();
    }

    /// <summary>
    /// While the HUD is hidden for a ghost, the numbered hotbar sits at <paramref name="index"/> in
    /// <paramref name="parent"/>, as stock's action row does, so ghost actions still work. Null puts it back in the deck.
    /// </summary>
    public void LendHotbar(Control? parent, int index = 0)
    {
        var hotbar = Bar.ActionsContainer;
        if (parent == null)
        {
            if (Bar.Parent == CustomSection)
                return;

            Bar.Orphan();
            CustomSection.AddChild(Bar);
            Bar.SetPositionInParent(CustomTitle.GetPositionInParent() + 1);
            ApplyLayout();
            return;
        }

        if (Bar.Parent == parent)
            return;

        Bar.Orphan();
        parent.AddChild(Bar);
        Bar.SetPositionInParent(Math.Min(index, parent.ChildCount - 1));
        hotbar.VisibleColumns = CFDeckLayout.TotalColumns;
        hotbar.VisibleRows = 1;
        hotbar.Page = 0;
    }

    private void ApplyLayout()
    {
        BasicGrid.SlotColumns = _widths[0];
        FeaturesGrid.SlotColumns = _widths[1];
        BasicGrid.SlotRows = _rows;
        FeaturesGrid.SlotRows = _rows;

        var hotbar = Bar.ActionsContainer;
        hotbar.VisibleRows = _rows;
        hotbar.VisibleColumns = _tab == CFDeckTab.All ? _widths[2] : CFDeckLayout.TotalColumns;

        ListScroll.SetSize = new Vector2(CFDeckLayout.Width(CFDeckLayout.TotalColumns), CFDeckLayout.Height(_rows));
        ListHolder.SetSize = ListScroll.SetSize;
        UpdatePagers();
    }

    private int MoveDivider(int divider, int steps)
    {
        var moved = _widths.Move(divider, steps);
        if (moved == 0)
            return 0;

        ApplyLayout();
        _config.SetCVar(CFCVars.HudDeckColumns, _widths.Save());
        _config.SaveToFile();
        return moved;
    }

    private void UpdatePagers()
    {
        UpdatePager(BasicGrid, BasicPager);
        UpdatePager(FeaturesGrid, FeaturesPager);

        var hotbar = Bar.ActionsContainer;
        CustomPager.SetCount(CFDeckLayout.PageCount(hotbar.SlotsInUse(), hotbar.VisibleColumns, hotbar.VisibleRows));
        hotbar.Page = CustomPager.Page;
    }

    private static void UpdatePager(CFDeckSlotGrid grid, CFDeckPager pager)
    {
        pager.SetCount(CFDeckLayout.PageCount(grid.ChildCount, grid.SlotColumns, grid.SlotRows));
        grid.Page = pager.Page;
    }

    private void SetLocked(bool locked)
    {
        Controller.CFLocked = locked;
        _config.SetCVar(CFCVars.HudDeckLocked, locked);
        _config.SaveToFile();
    }

    private void RefreshContents()
    {
        var actions = _entities.System<ActionsSystem>();
        CollectActions(actions);

        switch (_tab)
        {
            case CFDeckTab.All:
                ShowActions(BasicGrid, BasicKey, _common, actions);
                ShowActions(FeaturesGrid, FeaturesKey, FeaturesAndSpells(), actions);
                _listed.Clear();
                break;
            case CFDeckTab.Common:
                ShowActionList(_common, actions);
                break;
            case CFDeckTab.ClassFeatures:
                ShowActionList(_features, actions);
                break;
            case CFDeckTab.Spells:
                if (!_spellGroups.ContainsKey(_spellGroup) && _spellGroups.Count > 0)
                    _spellGroup = _spellGroups.Keys.First();

                UpdateRankButtons();
                ShowActionList(_spellGroups.GetValueOrDefault(_spellGroup) ?? new List<Entity<ActionComponent>>(), actions);
                break;
            default:
                _listed.Clear();
                break;
        }
    }

    private void CollectActions(ActionsSystem actions)
    {
        _common.Clear();
        _features.Clear();
        _spellGroups.Clear();
        foreach (var action in actions.GetClientActions())
        {
            _entities.TryGetComponent(action, out CFRadialSlotComponent? slot);
            _entities.TryGetComponent(action, out CFSpellComponent? spell);
            if (CFDeckSorter.Place(slot, spell) is not { } place)
                continue;

            switch (place.Tab)
            {
                case CFDeckTab.Common:
                    _common.Add(action);
                    break;
                case CFDeckTab.ClassFeatures:
                    _features.Add(action);
                    break;
                case CFDeckTab.Spells:
                    if (!_spellGroups.TryGetValue(place.SpellGroup, out var group))
                        _spellGroups[place.SpellGroup] = group = new List<Entity<ActionComponent>>();
                    group.Add(action);
                    break;
            }
        }

        SortByName(_common);
        SortByName(_features);
        foreach (var group in _spellGroups.Values)
            SortByName(group);
    }

    /// <summary>Class features first, then spells from cantrips up to focus spells.</summary>
    private List<Entity<ActionComponent>> FeaturesAndSpells()
    {
        var combined = new List<Entity<ActionComponent>>(_features);
        foreach (var group in _spellGroups.Values)
            combined.AddRange(group);

        return combined;
    }

    private void ShowActionList(List<Entity<ActionComponent>> listed, ActionsSystem actions)
    {
        _listed.Clear();
        foreach (var action in listed)
            _listed.Add(action.Owner);

        ShowActions(List, ListKey, listed, actions);
        EmptyLabel.Visible = listed.Count == 0;
    }

    /// <summary>
    /// The action a number key uses while Basic, Class or Spells is chosen: <paramref name="index"/> 0 to 9 is the first
    /// row, 10 to 19 (with Shift) the second. False on any other tab, where the keys work the numbered hotbar. True with
    /// no action when that place is empty, so the key does nothing rather than reach the hotbar.
    /// </summary>
    public bool TryKeyed(int index, out EntityUid? action)
    {
        action = null;
        if (!Keyed || index < 0 || index >= KeyedSlots)
            return false;

        if (index < _listed.Count)
            action = _listed[index];

        return true;
    }

    private bool Keyed => _tab is CFDeckTab.Common or CFDeckTab.ClassFeatures or CFDeckTab.Spells;

    /// <summary>Only remakes the buttons when the list changed, so a drag is not cut off.</summary>
    private void ShowActions(Control grid, int keyIndex, List<Entity<ActionComponent>> listed, ActionsSystem actions)
    {
        var key = new StringBuilder($"{_tab}:{_spellGroup}:");
        foreach (var action in listed)
            key.Append(action.Owner).Append(',');

        var text = key.ToString();
        if (text == _shownKeys[keyIndex])
            return;

        _shownKeys[keyIndex] = text;
        grid.RemoveAllChildren();
        var keys = ContentKeyFunctions.GetHotbarBoundKeys();
        for (var i = 0; i < listed.Count; i++)
        {
            var button = new ActionButton(_entities, Controller);
            Controller.RegisterDeckButton(button);
            button.UpdateData(listed[i], actions);
            if (grid == List && Keyed && i < keys.Length)
                button.KeyBind = keys[i];
            grid.AddChild(button);
        }
    }

    private void SortByName(List<Entity<ActionComponent>> actions)
    {
        actions.Sort((left, right) => string.Compare(ActionName(left), ActionName(right), StringComparison.CurrentCulture));
    }

    private void UpdateRankButtons()
    {
        for (var group = 0; group < _rankButtons.Length; group++)
        {
            var has = _spellGroups.ContainsKey(group);
            var button = _rankButtons[group];
            button.Disabled = !has;
            button.Pressed = group == _spellGroup && has;
        }
    }

    private void UpdateSlotStates()
    {
        var caster = _player.LocalEntity;
        RefreshOverlays(List, caster);
        RefreshOverlays(BasicGrid, caster);
        RefreshOverlays(FeaturesGrid, caster);
        RefreshOverlays(Bar.ActionsContainer, caster);
    }

    private void RefreshOverlays(Control grid, EntityUid? caster)
    {
        foreach (var child in grid.Children)
        {
            if (child is ActionButton button)
                CFActionOverlay.Refresh(button, _entities, caster);
        }
    }

    private string ActionName(EntityUid action)
    {
        return _entities.GetComponent<MetaDataComponent>(action).EntityName;
    }

    private static void SetIcon(Button button, char glyph, Font font)
    {
        button.Text = glyph.ToString();
        button.Label.FontOverride = font;
    }

    private static StyleBoxFlat Flat(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
            ContentMarginLeftOverride = 8,
            ContentMarginRightOverride = 8,
            ContentMarginTopOverride = 3,
            ContentMarginBottomOverride = 3,
        };
    }
}
