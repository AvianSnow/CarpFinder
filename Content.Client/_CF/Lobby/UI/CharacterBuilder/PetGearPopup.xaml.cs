using System.Linq;
using Content.Shared.CF.Companions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class PetGearPopup : DefaultWindow
{
    public event Action<List<string>>? OnFinished;

    private readonly List<CheckBox> _boxes = new();
    private readonly List<string> _ids = new();

    public PetGearPopup(IReadOnlyList<CFPetGearPrototype> gear, IReadOnlyList<string> selected)
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("cf-pet-gear-title");

        if (gear.Count == 0)
        {
            GearList.AddChild(new Label { Text = Loc.GetString("cf-pet-gear-empty") });
        }

        foreach (var piece in gear)
        {
            var box = new CheckBox
            {
                Pressed = selected.Contains(piece.ID),
            };
            box.Label.Text = piece.Name + " — " + piece.Summary;
            _boxes.Add(box);
            _ids.Add(piece.ID);
            GearList.AddChild(box);
        }

        FinishedButton.OnPressed += _ =>
        {
            var picked = new List<string>();
            for (var i = 0; i < _boxes.Count; i++)
            {
                if (_boxes[i].Pressed)
                    picked.Add(_ids[i]);
            }

            picked.Sort(StringComparer.Ordinal);
            OnFinished?.Invoke(picked);
            Close();
        };
        DismissButton.OnPressed += _ => Close();
    }
}
