using System.Numerics;
using Content.Shared.CF.Character;
using Content.Shared.CF.Companions;
using Content.Shared.CF.Preferences;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class PetTab : BoxContainer
{
    private HumanoidCharacterProfile? _profile;
    private IPrototypeManager? _prototypes;
    private Action<CFCharacterBuildData>? _onChanged;
    private CFPetKind _kind = CFPetKind.Companion;
    private string? _seenClass;
    private bool _allowCompanion;
    private bool _allowFamiliar;
    private DefaultWindow? _popup;

    public PetTab()
    {
        RobustXamlLoader.Load(this);
        TabCompanion.OnPressed += _ => SetKind(CFPetKind.Companion);
        TabFamiliar.OnPressed += _ => SetKind(CFPetKind.Familiar);
        BtnEditPet.OnPressed += _ => OpenEdit();
        BtnStatBlock.OnPressed += _ => OpenStatBlock();
        BtnViewSkills.OnPressed += _ => OpenSkills();
        BtnAddEquipment.OnPressed += _ => OpenGear();
        BtnBarding.OnPressed += _ => OpenBarding();
    }

    public bool Rebuild(
        HumanoidCharacterProfile? profile,
        IPrototypeManager prototypes,
        Action<CFCharacterBuildData> onChanged)
    {
        _profile = profile;
        _prototypes = prototypes;
        _onChanged = onChanged;
        if (profile == null)
            return false;

        var classId = profile.CFBuild.Class?.Id;
        _allowCompanion = CFPetMath.ClassHasCompanion(prototypes, classId);
        _allowFamiliar = CFPetMath.ClassHasFamiliar(prototypes, classId);
        TabCompanion.Visible = _allowCompanion;
        TabFamiliar.Visible = _allowFamiliar;
        if (!_allowCompanion && !_allowFamiliar)
            return false;

        if (classId != _seenClass)
        {
            _seenClass = classId;
            _kind = _allowCompanion ? CFPetKind.Companion : CFPetKind.Familiar;
            if (prototypes.TryIndex<CFPetPrototype>(profile.CFBuild.PetId, out var saved))
            {
                if (saved.Kind == CFPetKind.Companion && _allowCompanion)
                    _kind = CFPetKind.Companion;
                else if (saved.Kind == CFPetKind.Familiar && _allowFamiliar)
                    _kind = CFPetKind.Familiar;
            }
        }

        if (_kind == CFPetKind.Companion && !_allowCompanion)
            _kind = CFPetKind.Familiar;
        if (_kind == CFPetKind.Familiar && !_allowFamiliar)
            _kind = CFPetKind.Companion;

        TabCompanion.Pressed = _kind == CFPetKind.Companion;
        TabFamiliar.Pressed = _kind == CFPetKind.Familiar;
        Refresh();
        RememberShownPet();
        return true;
    }

    /// <summary>The species on the sheet is the one that spawns when the class actually grants that pet.</summary>
    private void RememberShownPet()
    {
        if (_profile == null || _prototypes == null || _onChanged == null)
            return;
        if (!string.IsNullOrEmpty(_profile.CFBuild.PetId))
            return;

        var shown = DisplayPet();
        if (shown == null || !CFPetMath.BuildGrants(_prototypes, _profile.CFBuild, shown.Kind))
            return;

        var build = _profile.CFBuild.Clone();
        build.PetId = shown.ID;
        _onChanged(build);
    }

    private void SetKind(CFPetKind kind)
    {
        if (kind == CFPetKind.Companion && !_allowCompanion)
            kind = CFPetKind.Familiar;
        if (kind == CFPetKind.Familiar && !_allowFamiliar)
            kind = CFPetKind.Companion;

        _kind = kind;
        TabCompanion.Pressed = kind == CFPetKind.Companion;
        TabFamiliar.Pressed = kind == CFPetKind.Familiar;
        Refresh();
    }

    private void Refresh()
    {
        var pet = DisplayPet();
        if (pet == null || _profile == null || _prototypes == null)
            return;

        var sheet = CFAttributeMath.Snapshot(_prototypes, _profile);
        var block = CFPetMath.Present(pet, _profile.CFBuild, sheet);
        PetTitle.Text = block.Title;
        AcValue.Text = block.ArmorClass.ToString();
        HpBar.MaxValue = Math.Max(1, block.HitPoints);
        HpBar.Value = block.HitPoints;
        HpLabel.Text = Loc.GetString("cf-pet-hp", ("current", block.HitPoints), ("max", block.HitPoints));
        ArmorLabel.Text = block.Armor;
        StrLabel.Text = Ability("STR", pet.Strength);
        DexLabel.Text = Ability("DEX", pet.Dexterity);
        ConLabel.Text = Ability("CON", pet.Constitution);
        IntLabel.Text = Ability("INT", pet.Intelligence);
        WisLabel.Text = Ability("WIS", pet.Wisdom);
        ChaLabel.Text = Ability("CHA", pet.Charisma);
        FortLabel.Text = Save("cf-pet-fortitude", block.Fortitude);
        RefLabel.Text = Save("cf-pet-reflex", block.Reflex);
        WillLabel.Text = Save("cf-pet-will", block.Will);
        PerLabel.Text = Save("cf-pet-perception", block.Perception);
        SpeedLabel.Text = Loc.GetString("cf-pet-speed", ("speed", block.Speed));
        SizeLabel.Text = Loc.GetString("cf-pet-size", ("size", block.Size));
        SensesLabel.Text = Loc.GetString("cf-pet-senses", ("senses", block.Senses));
        SupportLabel.SetMessage(Loc.GetString("cf-pet-support", ("text", block.Support)));
        AdvancedLabel.SetMessage(Loc.GetString("cf-pet-advanced", ("text", block.Advanced)));
        FillAttacks(block);
    }

    private void FillAttacks(CFPetBlock block)
    {
        AttackCards.RemoveAllChildren();
        if (block.Strikes.Count == 0)
        {
            AttackCards.AddChild(new Label { Text = Loc.GetString("cf-pet-no-strikes") });
            return;
        }

        foreach (var strike in block.Strikes)
            AttackCards.AddChild(StrikeCard(strike));
    }

    private Control StrikeCard(CFPetStrike strike)
    {
        var card = new PanelContainer();
        card.AddStyleClass("PanelDark");
        var box = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            Margin = new Thickness(8),
            SeparationOverride = 6,
        };
        var roll = new Button
        {
            Text = Loc.GetString("cf-pet-roll"),
            MinWidth = 60,
        };
        var captured = strike;
        roll.OnPressed += _ => ShowRoll(captured);
        box.AddChild(roll);

        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 12,
        };
        row.AddChild(new Label
        {
            Text = strike.Name,
            FontColorOverride = Color.FromHex("#e6c15a"),
        });
        row.AddChild(new Label
        {
            Text = Loc.GetString("cf-pet-hit", ("mod", CFAbilityScores.FormatModifier(strike.Attack))),
        });
        row.AddChild(new Label
        {
            Text = Loc.GetString("cf-pet-damage", ("dice", strike.Damage)),
            FontColorOverride = Color.FromHex("#8fbc8f"),
        });
        foreach (var trait in strike.Traits)
        {
            row.AddChild(new Label
            {
                Text = "[" + trait + "]",
                FontColorOverride = Color.FromHex("#a9a9a9"),
            });
        }

        box.AddChild(row);
        card.AddChild(box);
        return card;
    }

    private void ShowRoll(CFPetStrike strike)
    {
        var die = Random.Shared.Next(1, 21);
        var total = die + strike.Attack;
        Open(new PetInfoPopup(
            Loc.GetString("cf-pet-roll"),
            Loc.GetString("cf-pet-roll-result",
                ("name", strike.Name),
                ("roll", die),
                ("mod", CFAbilityScores.FormatModifier(strike.Attack)),
                ("total", total))));
    }

    private void OpenEdit()
    {
        var species = Species(_kind);
        if (species.Count == 0 || _profile == null)
            return;

        var shown = DisplayPet();
        var nickname = shown != null && _profile.CFBuild.PetId == shown.ID ? _profile.CFBuild.PetName : "";
        var popup = new PetEditPopup(species, shown?.ID, nickname);
        popup.OnFinished += (id, name) => Save(build =>
        {
            build.PetId = id;
            build.PetName = name;
        });
        Open(popup);
    }

    private void OpenStatBlock()
    {
        var block = CurrentBlock();
        if (block == null)
            return;

        var lines = new List<string>();
        lines.Add(block.Title + "  (" + block.Pet.Name + ")");
        lines.Add("Level " + block.Level + "  " + block.Size);
        lines.Add("AC " + block.ArmorClass + "  " + block.Armor);
        lines.Add("HP " + block.HitPoints);
        lines.Add(Ability("STR", block.Pet.Strength) + "   " + Ability("DEX", block.Pet.Dexterity) + "   " + Ability("CON", block.Pet.Constitution));
        lines.Add(Ability("INT", block.Pet.Intelligence) + "   " + Ability("WIS", block.Pet.Wisdom) + "   " + Ability("CHA", block.Pet.Charisma));
        foreach (var strike in block.Strikes)
        {
            var tags = strike.Traits.Count == 0 ? "" : " [" + string.Join("] [", strike.Traits) + "]";
            lines.Add(strike.Name + "  " + CFAbilityScores.FormatModifier(strike.Attack) + "  " + strike.Damage + tags);
        }

        if (block.Strikes.Count == 0)
            lines.Add(Loc.GetString("cf-pet-no-strikes"));

        lines.Add(Save("cf-pet-fortitude", block.Fortitude));
        lines.Add(Save("cf-pet-reflex", block.Reflex));
        lines.Add(Save("cf-pet-will", block.Will));
        lines.Add(Save("cf-pet-perception", block.Perception));
        lines.Add(Loc.GetString("cf-pet-speed", ("speed", block.Speed)));
        lines.Add(Loc.GetString("cf-pet-senses", ("senses", block.Senses)));
        lines.Add(Loc.GetString("cf-pet-support", ("text", block.Support)));
        lines.Add(Loc.GetString("cf-pet-advanced", ("text", block.Advanced)));
        lines.Add(block.Pet.Description);
        Open(new PetInfoPopup(Loc.GetString("cf-pet-stat-title"), string.Join("\n", lines)));
    }

    private void OpenSkills()
    {
        var block = CurrentBlock();
        if (block == null)
            return;

        var lines = new List<string>();
        lines.Add(Loc.GetString("cf-pet-skills-perception", ("mod", CFAbilityScores.FormatModifier(block.Perception))));
        foreach (var skill in block.Skills)
            lines.Add(skill.Name + "  " + CFAbilityScores.FormatModifier(skill.Modifier));

        if (block.Skills.Count == 0)
            lines.Add(Loc.GetString("cf-pet-skills-empty"));

        Open(new PetInfoPopup(Loc.GetString("cf-pet-skills-title"), string.Join("\n", lines)));
    }

    private void OpenGear()
    {
        if (_prototypes == null || _profile == null)
            return;

        var gear = new List<CFPetGearPrototype>();
        foreach (var piece in _prototypes.EnumeratePrototypes<CFPetGearPrototype>())
            gear.Add(piece);
        gear.Sort((left, right) => string.Compare(left.Name, right.Name, StringComparison.Ordinal));

        var popup = new PetGearPopup(gear, _profile.CFBuild.PetGear);
        popup.OnFinished += picked => Save(build =>
        {
            EnsureSpecies(build);
            build.PetGear = picked;
        });
        Open(popup);
    }

    private void OpenBarding()
    {
        if (_profile == null)
            return;

        var popup = new PetBardingPopup(_profile.CFBuild.PetBarding, _kind == CFPetKind.Familiar);
        popup.OnFinished += id => Save(build =>
        {
            EnsureSpecies(build);
            build.PetBarding = id;
        });
        Open(popup);
    }

    private void EnsureSpecies(CFCharacterBuildData build)
    {
        var shown = DisplayPet();
        if (shown == null)
            return;

        if (string.IsNullOrEmpty(build.PetId) || !_prototypes!.TryIndex<CFPetPrototype>(build.PetId, out var saved) || saved.Kind != _kind)
            build.PetId = shown.ID;
    }

    private CFPetBlock? CurrentBlock()
    {
        var pet = DisplayPet();
        if (pet == null || _profile == null || _prototypes == null)
            return null;

        return CFPetMath.Present(pet, _profile.CFBuild, CFAttributeMath.Snapshot(_prototypes, _profile));
    }

    private CFPetPrototype? DisplayPet()
    {
        if (_prototypes == null || _profile == null)
            return null;

        if (_prototypes.TryIndex<CFPetPrototype>(_profile.CFBuild.PetId, out var saved) && saved.Kind == _kind)
            return saved;

        CFPetPrototype? first = null;
        foreach (var pet in _prototypes.EnumeratePrototypes<CFPetPrototype>())
        {
            if (pet.Kind != _kind)
                continue;
            if (first == null || string.Compare(pet.Name, first.Name, StringComparison.Ordinal) < 0)
                first = pet;
        }

        return first;
    }

    private List<CFPetPrototype> Species(CFPetKind kind)
    {
        var list = new List<CFPetPrototype>();
        if (_prototypes == null)
            return list;

        foreach (var pet in _prototypes.EnumeratePrototypes<CFPetPrototype>())
        {
            if (pet.Kind == kind)
                list.Add(pet);
        }

        list.Sort((left, right) => string.Compare(left.Name, right.Name, StringComparison.Ordinal));
        return list;
    }

    private void Save(Action<CFCharacterBuildData> edit)
    {
        if (_profile == null || _onChanged == null)
            return;

        var build = _profile.CFBuild.Clone();
        edit(build);
        _onChanged(build);
    }

    private void Open(DefaultWindow window)
    {
        _popup?.Close();
        _popup = window;
        window.Open();
    }

    private static string Ability(string name, int modifier)
    {
        return Loc.GetString("cf-pet-ability", ("name", name), ("mod", CFAbilityScores.FormatModifier(modifier)));
    }

    private static string Save(string name, int modifier)
    {
        return Loc.GetString("cf-pet-save", ("name", Loc.GetString(name)), ("mod", CFAbilityScores.FormatModifier(modifier)));
    }
}
