using Content.Shared.Hands.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Input;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CF.Hud;

/// <summary>
/// The in-game bar: stock's inventory and hands row, with hit points and action diamonds across its top, Armor Class and
/// saves to its left, and the deck of actions above it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CFGameHud : UIWidget
{
    /// <summary>How long the deck takes to slide fully open or closed.</summary>
    private const float SlideSeconds = 0.16f;

    [Dependency] private IInputManager _input = default!;

    private readonly CFDeckDrawerState _drawer = new();
    private float _openness;
    private bool _combatant = true;

    public CFGameHud()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Ignore;
        LayoutContainer.SetGrowVertical(this, LayoutContainer.GrowDirection.Begin);
        LayoutContainer.SetGrowHorizontal(this, LayoutContainer.GrowDirection.Both);

        StatusPanelRight.SetSide(HandLocation.Right);
        StatusPanelLeft.SetSide(HandLocation.Left);

        LeftPanel.PanelOverride = Dark();
        BarPanel.PanelOverride = Dark();
        PipPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = new Color(12, 12, 16, 230) };
        HpBar.Fill = new Color(176, 28, 32);
        TempBar.Fill = new Color(36, 96, 196);

        ExpandButton.OnPressed += _ => _drawer.Press();
        Deck.PinChanged += pinned => _drawer.Pinned = pinned;
        _drawer.Pinned = Deck.Pinned;
        _drawer.Expanded = Deck.Pinned;
    }

    /// <summary>A body with no Pathfinder stats (a ghost, an animal) keeps its actions on show, and has no bars to fill.</summary>
    public void SetCombatant(bool combatant)
    {
        _combatant = combatant;
        LeftPanel.Visible = combatant;
        BarPanel.Visible = combatant;
        ExpandButton.Visible = combatant;
        Deck.SetCustomOnly(!combatant);
    }

    public void UpdatePanelEntityLeft(EntityUid? entity, Hand? hand)
    {
        StatusPanelLeft.Update(entity, hand);
    }

    public void UpdatePanelEntityRight(EntityUid? entity, Hand? hand)
    {
        StatusPanelRight.Update(entity, hand);
    }

    public void SetHighlightHand(HandLocation? hand)
    {
        StatusPanelLeft.UpdateHighlight(hand is HandLocation.Left);
        StatusPanelRight.UpdateHighlight(hand is HandLocation.Right);
    }

    public void UpdateStatusVisibility(bool left, bool right)
    {
        StatusPanelLeft.Visible = left;
        StatusPanelRight.Visible = right;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var mouse = (Vector2i) _input.MouseScreenPosition.Position;
        var overTab = ExpandButton.Visible && ExpandButton.GlobalPixelRect.Contains(mouse);
        var overFrame = GlobalPixelRect.Contains(mouse) || Deck.IsDragging;
        _drawer.Update(args.DeltaSeconds, overTab, overFrame);

        var open = _drawer.Expanded || !_combatant;
        ExpandButton.Text = Loc.GetString(open ? "cf-hud-deck-collapse" : "cf-hud-deck-expand");

        var target = open ? 1f : 0f;
        if (MathHelper.CloseToPercent(_openness, target))
            return;

        var step = args.DeltaSeconds / SlideSeconds;
        _openness = open ? Math.Min(1f, _openness + step) : Math.Max(0f, _openness - step);
        DeckClip.Openness = _openness;
    }

    private static StyleBoxFlat Dark()
    {
        return new StyleBoxFlat
        {
            BackgroundColor = new Color(32, 32, 38, 225),
            BorderColor = new Color(96, 96, 104, 220),
            BorderThickness = new Thickness(1),
        };
    }
}
