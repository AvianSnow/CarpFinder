using Content.Shared.CF.Character;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Character;

[GenerateTypedNameReferences]
public sealed partial class CFSheetSkillRow : BoxContainer
{
    public event Action? Pressed;
    public int ModifierValue { get; private set; }
    public string SkillId { get; private set; } = string.Empty;

    public CFSheetSkillRow()
    {
        RobustXamlLoader.Load(this);
        RollButton.OnPressed += _ => Pressed?.Invoke();
    }

    public void Set(string skillId, string name, string abilityAbbr, CFProficiencyRank rank, int modifier)
    {
        SkillId = skillId;
        ModifierValue = modifier;
        RollButton.Text = $"{name} ({abilityAbbr})";
        RankLabel.Text = RankLetter(rank);
        RankLabel.ToolTip = RankTooltip(rank);
        ModifierLabel.Text = modifier >= 0 ? $"+{modifier}" : modifier.ToString();
    }

    public static string RankLetter(CFProficiencyRank rank) => rank switch
    {
        CFProficiencyRank.Trained => "T",
        CFProficiencyRank.Expert => "E",
        CFProficiencyRank.Master => "M",
        CFProficiencyRank.Legendary => "L",
        _ => "U",
    };

    public static string RankTooltip(CFProficiencyRank rank) => rank switch
    {
        CFProficiencyRank.Trained => "Trained (+2)",
        CFProficiencyRank.Expert => "Expert (+4)",
        CFProficiencyRank.Master => "Master (+6)",
        CFProficiencyRank.Legendary => "Legendary (+8)",
        _ => "Untrained (+0)",
    };
}
