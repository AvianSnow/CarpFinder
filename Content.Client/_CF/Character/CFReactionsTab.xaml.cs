using System.Linq;
using Content.Shared.CF.Combat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Character;

/// <summary>
/// The character's reactions, in the order they get their chance. The arrows move one up or down, and the server is told
/// the new order. For each trigger, the first one that would change the outcome fires.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CFReactionsTab : BoxContainer
{
    [Dependency] private IEntityManager _entities = default!;

    private EntityUid _entity = EntityUid.Invalid;
    private List<string> _shown = new();

    public CFReactionsTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Update(EntityUid entity)
    {
        _entity = entity;
        _shown.Clear();
        Rebuild();
    }

    /// <summary>The order comes back from the server after a move, so the list redraws when it changes.</summary>
    public void FrameUpdate()
    {
        if (Entries() is { } entries && !entries.Select(entry => entry.Key).SequenceEqual(_shown))
            Rebuild();
    }

    private List<CFReactionEntry>? Entries()
    {
        return _entities.TryGetComponent(_entity, out CFReactionOrderComponent? order) ? order.Entries : null;
    }

    private void Rebuild()
    {
        Rows.RemoveAllChildren();
        var entries = Entries();
        _shown = entries?.Select(entry => entry.Key).ToList() ?? new List<string>();
        if (entries == null || entries.Count == 0)
        {
            Rows.AddChild(new Label { Text = Loc.GetString("cf-sheet-reactions-none"), StyleClasses = { "LabelSubText" } });
            return;
        }

        for (var i = 0; i < entries.Count; i++)
        {
            Rows.AddChild(Row(entries, i));
        }
    }

    private Control Row(List<CFReactionEntry> entries, int index)
    {
        var entry = entries[index];
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
        row.AddChild(new Label { Text = $"{index + 1}.", MinWidth = 28 });
        row.AddChild(new Label { Text = Loc.GetString(entry.Name), HorizontalExpand = true, ClipText = true });
        row.AddChild(new Label
        {
            Text = Loc.GetString("cf-sheet-reactions-level", ("level", entry.Level)),
            MinWidth = 70,
            StyleClasses = { "LabelSubText" },
        });

        var up = new Button { Text = "▲", MinWidth = 32, Disabled = index == 0 };
        up.OnPressed += _ => Move(index, -1);
        row.AddChild(up);

        var down = new Button { Text = "▼", MinWidth = 32, Disabled = index == entries.Count - 1 };
        down.OnPressed += _ => Move(index, 1);
        row.AddChild(down);
        return row;
    }

    private void Move(int index, int by)
    {
        var keys = new List<string>(_shown);
        var other = index + by;
        if (other < 0 || other >= keys.Count)
            return;

        (keys[index], keys[other]) = (keys[other], keys[index]);
        _entities.RaisePredictiveEvent(new CFReorderReactionsEvent { Keys = keys });
    }
}
