using Content.Shared.CF.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Shop;

/// <summary>
/// What a merchant's counter has bought, laid out like the shop. Each thing can be taken into the merchant's hands or
/// sold to the Merchants' Guild at full worth, since the merchant is a member.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CFCounterStoreWindow : DefaultWindow
{
    public event Action<NetEntity>? OnTake;
    public event Action<NetEntity?>? OnSell;

    private List<CFCounterEntry> _stored = new();

    public CFCounterStoreWindow()
    {
        RobustXamlLoader.Load(this);
        Header.AddChild(CFTradeTable.Header(
            (Loc.GetString("cf-counter-col-worth"), CFTradeTable.CostWidth),
            (string.Empty, CFTradeTable.ButtonWidth),
            (string.Empty, CFTradeTable.ButtonWidth)));
        SearchInput.OnTextChanged += _ => Refresh();
        SellAllButton.OnPressed += _ => OnSell?.Invoke(null);
    }

    public void UpdateState(CFMerchantCounterState state)
    {
        _stored = state.Stored;
        Refresh();
    }

    private void Refresh()
    {
        var search = SearchInput.Text.Trim();
        var total = 0;
        Rows.RemoveAllChildren();
        foreach (var entry in _stored)
        {
            total += entry.Copper;
            if (search.Length > 0 && !entry.Name.Contains(search, StringComparison.OrdinalIgnoreCase))
                continue;

            var item = entry.Item;
            Rows.AddChild(CFTradeTable.Item(entry,
                CFTradeTable.Cell(CFTradeTable.Price(entry.Copper), CFTradeTable.CostWidth),
                CFTradeTable.Button(Loc.GetString("cf-counter-take"), false, () => OnTake?.Invoke(item)),
                CFTradeTable.Button(Loc.GetString("cf-counter-sell"), entry.Copper <= 0, () => OnSell?.Invoke(item))));
        }

        EmptyLabel.Visible = _stored.Count == 0;
        TotalLabel.Text = Loc.GetString("cf-counter-stored-total", ("amount", CFCoins.FormatPrice(total)));
        SellAllButton.Disabled = total <= 0;
    }
}
