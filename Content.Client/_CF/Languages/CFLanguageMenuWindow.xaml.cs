using Content.Shared.CF.Languages;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CF.Languages;

/// <summary>
/// Lists the languages the player's body knows, with a button to speak each.
/// After <c>LanguageMenuWindow</c> in Starlight (https://github.com/ss14Starlight/space-station-14).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CFLanguageMenuWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly CFLanguageMenuSystem _languages;

    public CFLanguageMenuWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _languages = _entities.System<CFLanguageMenuSystem>();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _languages.LanguagesChanged += UpdateState;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _languages.LanguagesChanged -= UpdateState;
    }

    protected override void Opened()
    {
        base.Opened();
        UpdateState();
    }

    private void UpdateState()
    {
        var known = _languages.LocalLanguages;
        if (known == null || known.Known.Count == 0)
        {
            Show(null, new List<ProtoId<CFLanguagePrototype>>());
            return;
        }

        Show(CFLanguageSystem.Spoken(known), known.Known);
    }

    /// <summary>Draws the list. A null current language is a body with no languages.</summary>
    public void Show(ProtoId<CFLanguagePrototype>? current, IReadOnlyList<ProtoId<CFLanguagePrototype>> known)
    {
        CurrentLanguageLabel.Text = current is { } speaking
            ? Loc.GetString("cf-language-menu-current", ("language", NameOf(speaking)))
            : Loc.GetString("cf-language-menu-none");

        KnownList.RemoveAllChildren();
        foreach (var language in known)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 2,
                Margin = new Thickness(4, 2),
            };

            row.AddChild(new Label
            {
                Text = NameOf(language),
                MinWidth = 50,
                HorizontalExpand = true,
            });

            var button = new Button
            {
                Text = Loc.GetString("cf-language-menu-speak"),
                Disabled = language == current,
            };
            button.OnPressed += _ => Choose(language);
            row.AddChild(button);

            var panel = new PanelContainer();
            panel.StyleClasses.Add("PdaBorderRect");
            panel.AddChild(row);
            KnownList.AddChild(panel);
        }
    }

    private void Choose(ProtoId<CFLanguagePrototype> language)
    {
        _languages.RequestSpeak(language);

        // Show the choice at once. The server's answer redraws it.
        if (_languages.LocalLanguages is { } known)
            Show(language, known.Known);
    }

    private string NameOf(ProtoId<CFLanguagePrototype> id)
    {
        return _prototypes.TryIndex(id, out var language) ? Loc.GetString(language.Name) : id.Id;
    }
}
