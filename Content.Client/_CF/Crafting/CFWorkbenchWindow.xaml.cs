using Content.Shared.CF.Crafting;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CF.Crafting;

/// <summary>Known recipes on the left, the selected one and its materials on the right.</summary>
[GenerateTypedNameReferences]
public sealed partial class CFWorkbenchWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<ProtoId<CFCraftingRecipePrototype>>? OnCraft;

    private List<CFWorkbenchEntry> _entries = new();
    private ProtoId<CFCraftingRecipePrototype>? _selected;

    public CFWorkbenchWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchBar.OnTextChanged += _ => Rebuild();
        CraftButton.OnPressed += _ =>
        {
            if (_selected is { } recipe)
                OnCraft?.Invoke(recipe);
        };
    }

    public void UpdateState(CFWorkbenchState state)
    {
        _entries = state.Entries;
        _entries.Sort((a, b) => string.CompareOrdinal(ResultName(a), ResultName(b)));
        Rebuild();
    }

    private string ResultName(CFWorkbenchEntry entry)
    {
        return _prototypes.Index(_prototypes.Index(entry.Recipe).Result).Name;
    }

    private void Rebuild()
    {
        RecipeList.RemoveAllChildren();
        EmptyLabel.Visible = _entries.Count == 0;

        var filter = SearchBar.Text.Trim();
        CFWorkbenchEntry? selected = null;

        foreach (var entry in _entries)
        {
            if (entry.Recipe == _selected)
                selected = entry;

            var name = ResultName(entry);
            if (filter.Length > 0 && !name.Contains(filter, StringComparison.OrdinalIgnoreCase))
                continue;

            var button = new Button { Text = name, ToggleMode = false };
            if (!entry.HasMaterials || entry.Blocked != null)
                button.ModulateSelfOverride = Color.FromHex("#808080");

            var picked = entry;
            button.OnPressed += _ => Select(picked);
            RecipeList.AddChild(button);
        }

        if (selected is { } current)
            Select(current);
        else
            Clear();
    }

    private void Select(CFWorkbenchEntry entry)
    {
        _selected = entry.Recipe;

        var recipe = _prototypes.Index(entry.Recipe);
        var result = _prototypes.Index(recipe.Result);

        ItemView.SetPrototype(recipe.Result);
        ItemName.Text = recipe.ResultCount > 1 ? $"{result.Name} x{recipe.ResultCount}" : result.Name;
        ItemDescription.Text = result.Description;
        DcLabel.Text = Loc.GetString("cf-craft-window-dc", ("dc", entry.Dc));

        Requirements.RemoveAllChildren();
        foreach (var requirement in recipe.Requirements)
        {
            Requirements.AddChild(new Label { Text = requirement.Title(_prototypes) });
        }

        BlockedLabel.Visible = entry.Blocked != null;
        if (entry.Blocked != null)
            BlockedLabel.Text = Loc.GetString(entry.Blocked);

        CraftButton.Disabled = !entry.HasMaterials || entry.Blocked != null;
    }

    private void Clear()
    {
        _selected = null;
        ItemView.SetPrototype(null);
        ItemName.Text = string.Empty;
        ItemDescription.Text = string.Empty;
        DcLabel.Text = string.Empty;
        Requirements.RemoveAllChildren();
        BlockedLabel.Visible = false;
        CraftButton.Disabled = true;
    }
}
