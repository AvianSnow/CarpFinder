using Content.Shared.CF.Companions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class PetEditPopup : DefaultWindow
{
    public event Action<string, string>? OnFinished;

    private readonly List<CFPetPrototype> _species = new();

    public PetEditPopup(IReadOnlyList<CFPetPrototype> species, string? selectedId, string nickname)
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("cf-pet-edit-title");
        foreach (var pet in species)
            _species.Add(pet);

        for (var i = 0; i < _species.Count; i++)
            SpeciesButton.AddItem(_species[i].Name, i);

        var index = 0;
        for (var i = 0; i < _species.Count; i++)
        {
            if (_species[i].ID == selectedId)
                index = i;
        }

        if (_species.Count > 0)
        {
            SpeciesButton.SelectId(index);
            ShowDetails(index);
        }

        NicknameEdit.Text = nickname;
        SpeciesButton.OnItemSelected += args =>
        {
            SpeciesButton.SelectId(args.Id);
            ShowDetails(args.Id);
        };
        FinishedButton.OnPressed += _ => Finish();
        DismissButton.OnPressed += _ => Close();
    }

    private void Finish()
    {
        if (_species.Count == 0)
            return;

        OnFinished?.Invoke(_species[SpeciesButton.SelectedId].ID, NicknameEdit.Text.Trim());
        Close();
    }

    private void ShowDetails(int index)
    {
        if (index < 0 || index >= _species.Count)
            return;

        var pet = _species[index];
        DetailBody.SetMessage(pet.Name + "\n" + pet.Size + "\n\n" + pet.Description + "\n\n" + pet.Support);
    }
}
