using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class PetBardingPopup : DefaultWindow
{
    public event Action<string>? OnFinished;

    public PetBardingPopup(string current, bool familiar)
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("cf-pet-barding-title");

        var group = new ButtonGroup();
        NoneButton.Group = group;
        LightButton.Group = group;
        HeavyButton.Group = group;

        if (familiar)
        {
            NoneButton.Visible = false;
            LightButton.Visible = false;
            HeavyButton.Visible = false;
            FinishedButton.Visible = false;
            DetailLabel.Text = Loc.GetString("cf-pet-barding-familiar");
        }
        else
        {
            DetailLabel.Text = "";
            switch (current)
            {
                case "light":
                    LightButton.Pressed = true;
                    break;
                case "heavy":
                    HeavyButton.Pressed = true;
                    break;
                default:
                    NoneButton.Pressed = true;
                    break;
            }
        }

        FinishedButton.OnPressed += _ =>
        {
            var id = LightButton.Pressed ? "light" : HeavyButton.Pressed ? "heavy" : "";
            OnFinished?.Invoke(id);
            Close();
        };
        DismissButton.OnPressed += _ => Close();
    }
}
